def by_key(key: str) -> GameProfile | None:
    return GAMES.get(key)


def by_appid(appid) -> GameProfile | None:
    try:
        return BY_APPID.get(int(appid))
    except (TypeError, ValueError):
        return None


def by_name(name: str) -> GameProfile | None:
    if not name:
        return None
    low = name.strip().lower()
    for hint, key in _NAME_HINTS:
        if hint in low:
            return GAMES.get(key)
    return None


def identify(name: str = "", appid=None) -> GameProfile | None:
    return by_appid(appid) or by_name(name)


SUPPORT_RANK = [Support.NONE, Support.ACCOUNT, Support.EVENTS,
                Support.POSITIONAL, Support.FULL]


def supported(min_support: Support = Support.EVENTS) -> list:
    floor = SUPPORT_RANK.index(min_support)
    return [g for g in GAMES.values()
            if SUPPORT_RANK.index(g.support) >= floor]


def stats() -> dict:
    out = {str(s): 0 for s in SUPPORT_RANK}
    for g in GAMES.values():
        out[str(g.support)] += 1
    out["total"] = len(GAMES)
    return out


